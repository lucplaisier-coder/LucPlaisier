"""
step13_final_outputs.py: ROADMAP STEP 13, the final figures and tables.

    python -m src.step13_final_outputs

Plain-language summary
----------------------
NO NEW ANALYSIS. This script only reads results already saved by steps 5-12
and lays them out as the six core outputs of the control document (F.13) plus
the annex, with one consistent style and numbering, in outputs/final/. It also
writes docs/final_tables.md with every table formatted for the manuscript.

Core outputs (F.13):
  Table 1   Sample and vintage table
  Table 2   Predictive table (AUC, Brier, ECE)
  Figure 1  Reliability (2014 test; 2015 alongside)
  Figure 2  Net cash gain against selection rate (2014, display only)
  Figure 3  Permutation importance (HGB, 2014)
  Table 3   Main financial table at 80%, with bootstrap intervals (2014)
Annex A1-A8: 2015 robustness, grade groups, fee-0% sensitivity, sub-grade mix,
  odds ratios, all logit coefficients, success categories, input whitelist/blacklist.
"""

import shutil

import matplotlib
matplotlib.use("Agg")
from . import plotstyle  # noqa: F401  (same fonts on every computer)
import matplotlib.pyplot as plt
import pandas as pd

from . import config

R = config.REPO_ROOT / "outputs"
OUT = R / "final"
DOC = config.REPO_ROOT / "docs" / "final_tables.md"
APPROACH_ORDER = ["A. Fund-all", "B. Platform rule", "C. Logit", "D. HGB"]
COLORS = {"Logit": "#1f77b4", "HGB": "#ff7f0e"}


def pct(x, d=2):
    return "" if pd.isna(x) else f"{100 * x:.{d}f}%"


def cents(x, d=2):
    return "" if pd.isna(x) else f"{100 * x:+.{d}f} c" if x < 0 else f"{100 * x:.{d}f} c"


def dcents(x, d=3):
    return f"{100 * x:+.{d}f} c"


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in r.values) + " |")
    return "\n".join(lines)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    md = ["# Final tables and figures (roadmap step 13)", "",
          "Generated by `src/step13_final_outputs.py` from saved results only (no new analysis). "
          "Money is net cash gain per dollar invested over the loans' life, service fee 1% unless stated; "
          "c = cents. Selection = 80% of loans within each grade (F+G merged). "
          "Intervals: paired bootstrap, 1,000 draws, seed 42, 95% percentile.", ""]

    # ---- Table 1 -----------------------------------------------------------
    t1 = pd.read_csv(R / "step10" / "output1_sample_by_vintage.csv")
    f15 = pd.read_csv(R / "step11" / "financial_2015_q80.csv")
    t1.loc[t1.vintage == 2015, "charge_off_rate"] = f15.loc[f15.approach == "A. Fund-all", "charge_off_rate"].item()
    t1["charge_off_rate"] = t1["charge_off_rate"].astype(float)
    t1.to_csv(OUT / "table1_sample_by_vintage.csv", index=False, float_format="%.5f")
    md += ["## Table 1. Sample by vintage (36-month loans, final status)", "", md_table(pd.DataFrame({
        "Year": t1.vintage, "Role": t1.split, "Loans": t1.research_sample_loans.map("{:,}".format),
        "Resolved": t1.resolved_share.map(lambda x: pct(x, 2)),
        "Charge-off rate": t1.charge_off_rate.map(pct), "Mean rate": t1.mean_int_rate_working_pct.map("{:.2f}%".format)})),
        "", "Resolved = share of eligible loans with a final status (Fully Paid or Charged Off); the few "
        "unresolved 2015 loans are left out, as fixed in step 5.", ""]

    # ---- Table 2 -----------------------------------------------------------
    t2 = pd.read_csv(R / "step10" / "output2_predictive.csv")
    p15 = pd.read_csv(R / "step11" / "predictive_2015.csv")
    p15["year"] = "2015 robustness (final fit 2010-2013)"
    t2 = pd.concat([t2, p15[["year", "model", "auc", "brier", "ece"]]], ignore_index=True)
    t2.to_csv(OUT / "table2_predictive.csv", index=False, float_format="%.5f")
    md += ["## Table 2. Predictive performance", "", md_table(pd.DataFrame({
        "Period": t2.year, "Model": t2.model, "AUC": t2.auc.map("{:.3f}".format),
        "Brier": t2.brier.map("{:.4f}".format), "ECE (10 bins)": t2.ece.map("{:.3f}".format)})),
        "", "2013 rows come from the development fit and were used for tuning.", ""]

    # ---- Figure 1: reliability 2014 | 2015 --------------------------------
    fig, axes = plt.subplots(1, 2, figsize=(9, 4.4), dpi=150, sharex=True, sharey=True)
    for ax, (year, folder) in zip(axes, [(2014, "step9"), (2015, "step11")]):
        for m in ["Logit", "HGB"]:
            b = pd.read_csv(R / folder / f"reliability_bins_{m.lower()}_{year}.csv")
            ax.plot(b.mean_predicted, b.observed_default_rate, marker="o", ms=4, color=COLORS[m], label=m)
        ax.plot([0, 0.35], [0, 0.35], ls="--", lw=1, color="grey", label="perfect calibration")
        ax.set_title(f"{year} {'test' if year == 2014 else 'robustness'}", fontsize=10)
        ax.set_xlabel("Average predicted default probability")
    axes[0].set_ylabel("Observed charge-off rate")
    axes[0].legend(frameon=False, fontsize=8)
    fig.suptitle("Figure 1. Reliability (10 equal-size bins)", fontsize=11)
    fig.tight_layout()
    fig.savefig(OUT / "figure1_reliability_2014_2015.png")
    plt.close(fig)

    # ---- Figures 2 and 3 (already final; copied) ---------------------------
    shutil.copyfile(R / "step10" / "output4_selection_rate_curve_2014.png", OUT / "figure2_selection_rate_curve_2014.png")
    shutil.copyfile(R / "step10" / "output4_selection_rate_curve_2014.csv", OUT / "figure2_data.csv")
    shutil.copyfile(R / "step12" / "output5_permutation_importance_2014.png", OUT / "figure3_permutation_importance_2014.png")
    shutil.copyfile(R / "step12" / "hgb_permutation_importance_2014.csv", OUT / "figure3_data.csv")
    md += ["## Figures", "", "* Figure 1: `outputs/final/figure1_reliability_2014_2015.png`",
           "* Figure 2: `outputs/final/figure2_selection_rate_curve_2014.png` (display only; the result is judged at 80%)",
           "* Figure 3: `outputs/final/figure3_permutation_importance_2014.png`", ""]

    # ---- Table 3: main financial table 2014 --------------------------------
    def money_block(fin, boot, year, title):
        fin = fin.set_index("approach").loc[APPROACH_ORDER].reset_index()
        a = pd.DataFrame({"Approach": fin.approach, "Loans funded": fin.loans.map("{:,}".format),
                          "Charge-off rate": fin.charge_off_rate.map(pct),
                          "Principal loss rate": fin.principal_loss_rate.map(pct),
                          "Net cash gain per $": fin.net_cash_gain_per_dollar.map(cents),
                          "Mean rate": fin.mean_int_rate_pct.map("{:.2f}%".format)})
        b = boot[boot.metric.isin(["net_cash_gain_per_dollar", "charge_off_rate", "principal_loss_rate"])].copy()
        fmt = lambda r: (dcents(r.difference) + f" [{dcents(r.ci95_low)}, {dcents(r.ci95_high)}]"
                         if r.metric == "net_cash_gain_per_dollar"
                         else f"{100*r.difference:+.2f} pts [{100*r.ci95_low:+.2f}, {100*r.ci95_high:+.2f}]")
        b["text"] = b.apply(fmt, axis=1)
        piv = b.pivot(index="contrast", columns="metric", values="text")
        order = [c for c in ["D. HGB minus C. Logit", "D. HGB minus B. Platform rule", "C. Logit minus B. Platform rule",
                             "D. HGB minus A. Fund-all", "C. Logit minus A. Fund-all",
                             "B. Platform rule minus A. Fund-all"] if c in piv.index]
        piv = piv.loc[order]
        role = {"D. HGB minus C. Logit": "primary", "D. HGB minus B. Platform rule": "primary"}
        c = pd.DataFrame({"Comparison": piv.index, "Role": [role.get(i, "secondary") for i in piv.index],
                          "Net cash gain per $ [95%]": piv["net_cash_gain_per_dollar"].values,
                          "Charge-off rate [95%]": piv["charge_off_rate"].values,
                          "Principal loss [95%]": piv["principal_loss_rate"].values})
        auc = boot[boot.metric == "auc"].iloc[0]
        a.to_csv(OUT / f"{title}_levels_{year}.csv", index=False)
        c.to_csv(OUT / f"{title}_contrasts_{year}.csv", index=False)
        return a, c, auc

    a14, c14, auc14 = money_block(pd.read_csv(R / "step9" / "financial_2014_q80.csv"),
                                  pd.read_csv(R / "step9" / "bootstrap_contrasts_2014.csv"), 2014, "table3_financial")
    md += ["## Table 3. Main financial result, 2014 test (80% within grade)", "", md_table(a14), "",
           md_table(c14), "",
           f"HGB minus Logit AUC: {auc14.difference:+.4f} [{auc14.ci95_low:+.4f}, {auc14.ci95_high:+.4f}].", ""]

    # ---- Annex -------------------------------------------------------------
    md += ["# Annex", ""]
    a15, c15, auc15 = money_block(f15, pd.read_csv(R / "step11" / "bootstrap_contrasts_2015.csv"), 2015,
                                  "annexA1_financial")
    md += ["## A1. 2015 robustness (same frozen models and rules)", "", md_table(a15), "", md_table(c15), "",
           f"HGB minus Logit AUC: {auc15.difference:+.4f} [{auc15.ci95_low:+.4f}, {auc15.ci95_high:+.4f}].", ""]

    gg = pd.read_csv(R / "step11" / "grade_groups_2014_2015.csv")
    gg.to_csv(OUT / "annexA2_grade_groups.csv", index=False)
    piv = gg.pivot_table(index=["year", "grade_group"], columns="approach", values="net_cash_gain_per_dollar")
    pco = gg.pivot_table(index=["year", "grade_group"], columns="approach", values="charge_off_rate")
    tab = pd.DataFrame({"Year": [i[0] for i in piv.index], "Group": [i[1] for i in piv.index]})
    for a in APPROACH_ORDER:
        tab[a] = [f"{cents(g)} / {pct(c, 1)}" for g, c in zip(piv[a], pco[a])]
    md += ["## A2. Grade groups (net cash gain per $ / charge-off rate; point estimates)", "", md_table(tab), ""]

    s0 = pd.concat([pd.read_csv(R / "step9" / "bootstrap_contrasts_2014.csv").assign(year=2014),
                    pd.read_csv(R / "step11" / "bootstrap_contrasts_2015.csv").assign(year=2015)])
    s0 = s0[s0.metric == "net_cash_gain_per_dollar_sf0"]
    s0.to_csv(OUT / "annexA3_fee0_sensitivity.csv", index=False, float_format="%.6f")
    md += ["## A3. Sensitivity: service fee 0%", "", md_table(pd.DataFrame({
        "Year": s0.year, "Comparison": s0.contrast,
        "Net cash gain per $ [95%]": [f"{dcents(d)} [{dcents(l)}, {dcents(h)}]"
                                     for d, l, h in zip(s0.difference, s0.ci95_low, s0.ci95_high)]})), ""]

    mix = pd.read_csv(R / "step10" / "annex_subgrade_mix_2014.csv")
    mix.to_csv(OUT / "annexA4_subgrade_mix_2014.csv", index=False)
    mix_md = mix.copy()
    for a in APPROACH_ORDER:
        mix_md[a] = mix_md[a].map(lambda x: pct(x, 1))
    md += ["## A4. Sub-grade mix of funded loans, 2014", "", md_table(mix_md.rename(columns={"sub_grade": "Sub-grade"})), ""]

    orr = pd.read_csv(R / "step12" / "logit_odds_ratios_per_sd.csv")
    orr.to_csv(OUT / "annexA5_logit_odds_ratios.csv", index=False)
    md += ["## A5. Logit odds ratios per 1 SD (final fit 2010-2013; holding sub-grade and rate fixed)", "",
           md_table(pd.DataFrame({"Input": orr.label, "1 SD": orr.sd_2010_2013.map("{:,.2f}".format),
                                  "Odds ratio": orr.odds_ratio_per_sd.map("{:.3f}".format)})), ""]
    shutil.copyfile(R / "step12" / "annex_logit_all_coefficients_final_fit.csv", OUT / "annexA6_logit_all_coefficients.csv")
    md += ["## A6. All logit coefficients (final fit; only A5 rows are interpreted)", "",
           "See `outputs/final/annexA6_logit_all_coefficients.csv`.", ""]

    cats = pd.DataFrame({"Category (F.11)": pd.read_csv(R / "step9" / "success_categories_2014.csv").iloc[:, 0],
                         "2014 test": pd.read_csv(R / "step9" / "success_categories_2014.csv")["applies"].map({True: "applies", False: "-"}),
                         "2015 (consistency only)": pd.read_csv(R / "step11" / "success_categories_2015.csv")["applies"].map({True: "applies", False: "-"})})
    cats.to_csv(OUT / "annexA7_success_categories.csv", index=False)
    md += ["## A7. Pre-registered success categories", "", md_table(cats), ""]

    wl = pd.read_csv(R / "step10" / "annex_inputs_whitelist.csv")
    bl = pd.DataFrame({"input": ["loan_status", "total_pymnt*, total_rec_*, recoveries, collection_recovery_fee",
                                 "last_pymnt_*, next_pymnt_d, out_prncp*, last_credit_pull_d, last_fico_range_*",
                                 "pymnt_plan, hardship_*, debt_settlement_*, settlement_*, funded_amnt_inv",
                                 "verification_status", "grade", "term, installment",
                                 "id, member_id, url, desc, title, emp_title, zip_code, addr_state, policy_code"],
                       "status": ["target only", "outcome (post-origination)", "post-origination",
                                  "post-origination", "excluded (timing, G2-VERIFY-EXCLUDE)",
                                  "selection stratum only", "constant / determined by amount, rate, term",
                                  "identifiers, free text, location, filter"]})
    pd.concat([wl[["input", "status"]], bl]).to_csv(OUT / "annexA8_inputs_whitelist_blacklist.csv", index=False)
    md += ["## A8. Inputs: whitelist (frozen) and blacklist", "",
           md_table(pd.concat([wl[["input", "status"]], bl]).rename(columns={"input": "Field", "status": "Role"})), ""]

    DOC.write_text("\n".join(md) + "\n")
    print(f"Final outputs in {OUT} and {DOC}")


if __name__ == "__main__":
    main()
